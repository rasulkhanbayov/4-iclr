#!/usr/bin/env python3
"""
Sensitivity check (CPU, 2026-11-28, after the main runs were seen): where the fit's lost-frame check applies.

`fits.fit_theta` returns no estimate if the track is missing in ANY frame of the clip, and it applies that
check before cutting the track at floor contact. The fit itself uses only the frames before contact
(projectile, inclined slide). So a ball lost after it lands (it leaves the frame, or dips below the floor
line where pixels are masked) makes the clip invalid_fit although the fitted frames are clean.

This script re-scores every clip from its STORED tracks and shape statistics under both rules and counts
label changes:
  registered  the rule as run (lost frame anywhere -> no fit)
  window      lost frames only matter inside the fitted frames (after the given prefix, before contact)
Both rules are applied to the same stored (0.01 px rounded) tracks, so rounding does not enter the
comparison. Shape, camera and static checks are unchanged (they still count every frame). The registered
rule stays the primary measurement; this reports how much the choice matters.

Usage:  python experiments/v2_lostframe_check.py [--runs main_text shaded_text main_frame]
Writes: <REVISION>/results_v2/lostframe_check.{json,md}
"""

from __future__ import annotations

import argparse
import collections
import json
import os
import sys

CODE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, CODE_DIR)

import numpy as np

from physweep.fits import MIN_FIT_FRAMES, contact_index, fit_theta
from physweep.runio import load_latest, raw_files
from physweep.validity import classify

RESULTS = os.path.join(os.path.dirname(CODE_DIR), "results_v2")


def finite(x):
    return x is not None and np.isfinite(x)


def track(rec, key):
    v = rec.get(key)
    return None if v is None else np.where(np.asarray(v, float) < 0, np.nan, np.asarray(v, float))


def fit_registered(system, cx, cy, dt, g):
    return (float("nan"), 0.0) if cx is None else fit_theta(system, cx, cy, dt, ground_row=g)


def fit_window(system, cx, cy, dt, g):
    if cx is None:
        return float("nan"), 0.0
    if system in ("projectile", "inclined_slide"):
        k = contact_index(cy, g)
        if k < MIN_FIT_FRAMES:
            return float("nan"), 0.0
        cx, cy = cx[:k], cy[:k]
    return fit_theta(system, cx, cy, dt, ground_row=None)


def label(fn, rec):
    k = rec.get("n_given") or 0
    dt = rec.get("dt") or 1.0 / rec["fps"]
    g = rec["ground_row0"]
    h, r2 = fn(rec["system"], track(rec, "blob_cx")[k:], track(rec, "blob_cy")[k:], dt, g)
    cx = track(rec, "cot_cx")
    h2, r2b = (fn(rec["system"], cx[k:], track(rec, "cot_cy")[k:], dt, g) if cx is not None else (None, None))
    return classify(rec["system"], rec, h if finite(h) else None, r2, h2 if finite(h2) else None, r2b)["label"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-root", default=os.environ.get("PHYSWEEP_OUT", os.path.join(CODE_DIR, "..", "runs")))
    ap.add_argument("--runs", nargs="+", default=["main_text", "shaded_text", "main_frame"])
    ap.add_argument("--results", default=RESULTS)
    a = ap.parse_args()
    res = {}
    for run in a.runs:
        for model in sorted(os.listdir(os.path.join(a.out_root, run))):
            mdir = os.path.join(a.out_root, run, model)
            if not os.path.isdir(mdir) or not raw_files(mdir):
                continue
            recs = [r for r in load_latest(mdir, prefer_rescored=True).values() if "error" not in r]
            trans, reproduced = collections.Counter(), 0
            for r in recs:
                lo, ln = label(fit_registered, r), label(fit_window, r)
                reproduced += lo == r["label"]
                if lo != ln:
                    trans[f"{r['system']}: {lo} -> {ln}"] += 1
            res[f"{run}/{model}"] = dict(
                n_clips=len(recs), valid_stored=sum(r["label"] == "valid" for r in recs),
                registered_rule_reproduces_stored_label=reproduced,
                to_valid=sum(v for k, v in trans.items() if k.endswith("-> valid")),
                from_valid=sum(v for k, v in trans.items() if ": valid ->" in k),
                fit_to_shape=sum(v for k, v in trans.items() if "invalid_fit -> invalid_shape" in k),
                changes=dict(trans))
    tot = {run: {k: sum(d[k] for key, d in res.items() if key.startswith(run + "/"))
                 for k in ("n_clips", "valid_stored", "to_valid", "from_valid", "fit_to_shape")} for run in a.runs}
    os.makedirs(a.results, exist_ok=True)
    stem = os.path.join(a.results, "lostframe_check")
    with open(stem + ".json", "w") as fh:
        json.dump(dict(per_model=res, totals=tot), fh, indent=1)
    out = ["# Lost-frame rule: registered vs. fitted-window (sensitivity check)", "",
           "Generated by `experiments/v2_lostframe_check.py`. Registered rule: a lost frame anywhere in the clip "
           "means no fit. Window rule: only lost frames inside the fitted frames count. Both rules on the same "
           "stored tracks; shape/camera/static checks unchanged.", "",
           "| run | clips | valid (registered) | → valid under window rule | valid → invalid | invalid_fit → invalid_shape |",
           "|---|---|---|---|---|---|"]
    for run, t in tot.items():
        out.append(f"| {run} | {t['n_clips']} | {t['valid_stored']} | {t['to_valid']} | {t['from_valid']} | "
                   f"{t['fit_to_shape']} |")
    out += ["", "| run / model | registered rule reproduces stored label | changes |", "|---|---|---|"]
    for k, d in res.items():
        out.append(f"| {k} | {d['registered_rule_reproduces_stored_label']}/{d['n_clips']} | "
                   + ("; ".join(f"{c}: {n}" for c, n in sorted(d["changes"].items())) or "none") + " |")
    md = "\n".join(out)
    with open(stem + ".md", "w") as fh:
        fh.write(md + "\n")
    print(md)


if __name__ == "__main__":
    main()
